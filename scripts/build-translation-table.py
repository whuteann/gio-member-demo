#!/usr/bin/env python3
"""Generate TRANSLATIONS.md — every UI string in English, Chinese and Malay,
one table per namespace file.

Generated, not hand-maintained: the table is for review, and a review table
that drifts from the JSON it describes is worse than none. Re-run it after
any locale edit.

    python3 scripts/build-translation-table.py

Keys are flattened with dots, exactly as `t()` addresses them, so a row can
be pasted straight into a call site. Array values (i18next `returnObjects`)
are indexed — `tips.0`, `tips.1` — because that is how they are actually
reached. Missing or identical-to-English values are called out rather than
silently rendered: an untranslated string looks the same as a correctly
translated one in a table like this, and the point of the table is to catch
exactly that.
"""

import json
import pathlib
import sys

LOCALES_DIR = pathlib.Path(__file__).resolve().parent.parent / "public" / "locales"
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "TRANSLATIONS.md"

LANGS = [("en", "English"), ("zh", "Chinese"), ("ms", "Malay")]
BASE = "en"


def flatten(value, prefix=""):
    """{"a": {"b": "x"}} -> {"a.b": "x"}; lists -> "a.0", "a.1"."""
    out = {}
    if isinstance(value, dict):
        for key, child in value.items():
            out.update(flatten(child, f"{prefix}.{key}" if prefix else key))
    elif isinstance(value, list):
        for i, child in enumerate(value):
            out.update(flatten(child, f"{prefix}.{i}"))
    else:
        out[prefix] = value
    return out


def cell(text):
    """Make a value safe inside a Markdown table cell."""
    if text is None:
        return "_(missing)_"
    text = str(text)
    # A literal pipe would end the cell; a newline would end the row.
    text = text.replace("|", "\\|").replace("\n", "<br>")
    # Leave {{interpolations}} and <0>tags</0> visible — a reviewer needs to
    # see that the placeholders match across the three languages.
    return text or "_(empty)_"


def main():
    namespaces = sorted(p.name for p in (LOCALES_DIR / BASE).glob("*.json"))
    if not namespaces:
        sys.exit(f"No locale files under {LOCALES_DIR / BASE}")

    loaded = {}
    for code, _ in LANGS:
        for ns in namespaces:
            path = LOCALES_DIR / code / ns
            data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
            loaded[(code, ns)] = flatten(data)

    total = 0
    missing = []   # (ns, key, lang)
    untranslated = []  # (ns, key, lang) — present but byte-identical to English

    lines = [
        "# Auren — UI translation reference",
        "",
        "Every translatable UI string in the member app, in all three supported",
        "languages, grouped by namespace file. One row per `t()` key.",
        "",
        "Generated by `scripts/build-translation-table.py` from",
        "`public/locales/{en,zh,ms}/*.json` — **edit the JSON, not this file**,",
        "then re-run the script.",
        "",
        "The Malay column is a **first draft written for review** — that is what",
        "this file is for. [Needs attention](#needs-attention) at the bottom",
        "lists anything missing, or identical to the English, as a starting",
        "point for that review.",
        "",
        "This file covers *UI copy only*. AI-generated content (readings, Core",
        "Personality, recommendation letters) is not here — it is written per",
        "request by the model in the user's language and stored in the database;",
        "see `MALAY_LANGUAGE_PLAN.md`.",
        "",
        "## Contents",
        "",
    ]

    for ns in namespaces:
        anchor = ns.replace(".json", "").lower()
        lines.append(f"- [`{ns}`](#{anchor}) — {len(loaded[(BASE, ns)])} keys")
    lines += ["- [Needs attention](#needs-attention)", ""]

    body = []
    for ns in namespaces:
        base_keys = loaded[(BASE, ns)]
        total += len(base_keys)
        body += ["---", "", f"## {ns.replace('.json', '')}", "",
                 f"`public/locales/*/{ns}` — {len(base_keys)} keys", "",
                 "| Key | English | Chinese | Malay |",
                 "| --- | --- | --- | --- |"]
        for key in base_keys:
            row = [f"`{key}`"]
            for code, _ in LANGS:
                value = loaded[(code, ns)].get(key)
                if value is None:
                    missing.append((ns, key, code))
                elif code != BASE and str(value) == str(base_keys[key]) and str(value).strip():
                    untranslated.append((ns, key, code))
                row.append(cell(value))
            body.append("| " + " | ".join(row) + " |")
        body.append("")

        extra = set()
        for code, _ in LANGS:
            extra |= set(loaded[(code, ns)]) - set(base_keys)
        if extra:
            body += [f"> **{len(extra)} key(s) present in a translation but not in English**"
                     f" — stale, safe to delete: {', '.join(f'`{k}`' for k in sorted(extra))}", ""]

    lines += body
    lines += ["---", "", "## Needs attention", ""]
    if not missing and not untranslated:
        lines += ["Nothing — all three languages have a distinct value for every key.", ""]
    else:
        if missing:
            lines += [f"### Missing ({len(missing)})", "",
                      "No value at all in that language; the app falls back to English.", "",
                      "| Namespace | Key | Language |", "| --- | --- | --- |"]
            lines += [f"| `{ns}` | `{k}` | {lang} |" for ns, k, lang in missing] + [""]
        if untranslated:
            lines += [f"### Identical to English ({len(untranslated)})", "",
                      "Present but byte-identical to the English. This is a heuristic,",
                      "not a defect list — a match is often correct: brand terms",
                      "(\"Auren\", \"Premium\"), bare tokens (`{{count}} XP`, `-20%`,",
                      "`GID: {{gid}}`), language names deliberately shown in their own",
                      "script, and coincidences (the Malay weekday initial for Sabtu is",
                      "\"S\", same as Saturday). Scan it for anything that is genuinely",
                      "English prose sitting in a translated file.", "",
                      "| Namespace | Key | Language | Value |", "| --- | --- | --- | --- |"]
            lines += [
                f"| `{ns}` | `{k}` | {lang} | {cell(loaded[(lang, ns)].get(k))} |"
                for ns, k, lang in untranslated
            ] + [""]

    lines += ["---", "",
              f"**{total} keys × {len(LANGS)} languages = {total * len(LANGS)} strings** "
              f"across {len(namespaces)} namespace files.", ""]

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(OUTPUT.parent.parent)}")
    print(f"  {total} keys across {len(namespaces)} namespaces ({total * len(LANGS)} strings)")
    print(f"  missing: {len(missing)}   identical-to-English: {len(untranslated)}")


if __name__ == "__main__":
    main()
